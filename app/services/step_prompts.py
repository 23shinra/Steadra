def step_prompt_for(step_key: str, mode: str) -> str:
    key = (step_key or "").lower().strip()
    block = STEP_LEVEL_PROMPTS.get(key, {})
    if mode == "coach":
        return block.get("coach") or DEFAULT_COACH
    return block.get("validation") or DEFAULT_VALIDATION


STEP_KEY_ALIASES = {
    "idea_polling": "idea_poll",
    "pre_mvp_pitch": "pitch_pre",
    "pitch_pre_mvp": "pitch_pre",
    "pitch_check": "pitch",
    "pitch_validated": "pitch",
}


def infer_step_key(step: dict) -> str:
    key = (step.get("key") or "").lower().strip()
    key = STEP_KEY_ALIASES.get(key, key)
    if key in STEP_LEVEL_PROMPTS:
        return key
    label = (step.get("label") or "").lower()
    if "опрос" in label or "poll" in label or "гипотез" in label:
        return "idea_poll"
    if any(x in label for x in ("преза", "презент")) and any(
        x in label for x in ("без", "pre", "до mvp", "pre-mvp", "premvp", "pre mvp")
    ):
        return "pitch_pre"
    if "питч" in label or "pitch" in label or "дек" in label or "презент" in label or "преза" in label:
        return "pitch"
    if "фин" in label or "модел" in label or "unit" in label:
        return "finmodel"
    if "mvp" in label or "прототип" in label or "лендинг" in label:
        return "mvp"
    if "пользов" in label or "клиент" in label:
        return "users"
    if "traction" in label or "продаж" in label or "выруч" in label or "оплат" in label:
        return "traction"
    if "тоо" in label or "юр" in label or "регистр" in label:
        return "too"
    if "денег" in label or "деньги" in label or "инвест" in label or "канал" in label:
        return "money"
    return key or "step"
