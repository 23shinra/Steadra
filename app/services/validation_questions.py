def milestone_for_step_key(step_key: str | None) -> dict[str, Any] | None:
    mid = MILESTONE_BY_STEP.get((step_key or "").lower().strip())
    if not mid:
        return None
    return MILESTONES.get(mid)


def questions_flat(milestone: dict[str, Any]) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    for group in milestone.get("groups") or []:
        out.extend(group.get("questions") or [])
    return out


def killer_questions(milestone: dict[str, Any]) -> list[tuple[int, str]]:
    ids = set(milestone.get("killer_ids") or [])
    return [(qid, text) for qid, text in questions_flat(milestone) if qid in ids]


def validation_prompt_block(step_key: str | None) -> str:
    """Compact criteria + killer questions for AI step validation."""
    milestone = milestone_for_step_key(step_key)
    if not milestone:
        return ""
    killers = killer_questions(milestone)
    lines = [
        f"Отправная точка «{milestone['title']}».",
        f"Критерий успеха: {milestone['criterion']}",
        "Убийственные вопросы — отчёт должен закрывать их фактами (не обещаниями):",
    ]
    for qid, text in killers:
        lines.append(f"{qid}. {text}")
    lines.append(
        "Если в отчёте нет ответов/доказательств по убийственным вопросам — отклоняй "
        "(approved=false) и перечисли missing_criteria номерами вопросов."
    )
    return "\n".join(lines)


def all_milestones_summary() -> list[dict[str, str]]:
    return [
        {
            "id": m["id"],
            "title": m["title"],
            "criterion": m["criterion"],
            "step_key": m["step_key"],
        }
        for m in MILESTONES.values()
    ]
